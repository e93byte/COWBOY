import { test, expect } from '@playwright/test';
test('slip rejects invalid stake, correlated combinations and stale review', async ({ page }) => {
 await page.goto('/');
 await page.getByRole('button', { name: 'Review ticket' }).click();
 await expect(page.getByRole('status')).toContainText('selection');
 await page.getByRole('button', { name: 'Open Buffalo at Miami' }).click();
 await page.getByRole('button', { name: 'Buffalo wins · 1.90' }).click();
 await page.getByLabel('Stake · virtual credits').fill('-1');
 await page.getByRole('button', { name: 'Review ticket' }).click();
 await expect(page.getByRole('status')).toContainText('Stake');
 await page.getByLabel('Stake · virtual credits').fill('10');
 await page.getByRole('button', { name: 'Over 47.5 points · 2.00' }).click();
 await page.getByRole('button', { name: 'Review ticket' }).click();
 await expect(page.getByRole('status')).toContainText('Same-event');
 await page.getByRole('button', { name: 'Remove football-over' }).click();
 await page.getByRole('button', { name: 'Review ticket' }).click();
 await page.getByRole('button', { name: 'Advance scenario' }).click();
 await page.getByRole('button', { name: 'Accept practice ticket' }).click();
 await expect(page.getByRole('status')).toContainText('changed');
 await expect(page.getByTestId('sports-balance')).toHaveText('500.00');
});
